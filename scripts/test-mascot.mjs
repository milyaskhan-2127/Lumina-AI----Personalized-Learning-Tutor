import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import ts from 'typescript';
import assert from 'node:assert/strict';
globalThis.localStorage={getItem:()=>null,setItem:()=>{}};
const folder=path.resolve('output/mascot-tests');
await mkdir(folder,{recursive:true});
const source=await readFile('src/mascot/useMascotStore.ts','utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const target=path.join(folder,'store.mjs');await writeFile(target,compiled);
const {useMascotStore,dispatchMascot}=await import(pathToFileURL(target));
const store=()=>useMascotStore.getState();
store().setPointer(5,-6);assert.deepEqual(store().screenPointer,{x:1,y:-1});
store().setPointer(-.6,.8);assert.deepEqual(store().screenPointer,{x:-.6,y:.8});
dispatchMascot({type:'agent.started'});assert.equal(store().state,'thinking');
dispatchMascot({type:'document.processing',detail:'test.pdf'});assert.equal(store().state,'reading');
store().setActivity('hover',{state:'hover',message:'Hover'});assert.equal(store().state,'reading');
store().setActivity('microphone',{state:'listening',message:'Microphone active'});assert.equal(store().state,'listening');
dispatchMascot({type:'agent.failed',detail:'Network failed'});assert.equal(store().state,'error');
store().setActivity('error',null);assert.equal(store().state,'listening');
store().setActivity('microphone',null);assert.equal(store().state,'reading');
dispatchMascot({type:'document.completed'});assert.notEqual(store().state,'reading');
store().setActivity('notice',null);store().setActivity('hover',null);
dispatchMascot({type:'agent.started'});dispatchMascot({type:'agent.responding'});assert.equal(store().state,'teaching');
dispatchMascot({type:'agent.completed'});store().setActivity('notice',null);assert.equal(store().state,'idle');
store().setActivity('speech',{state:'talking',message:'Audio playback active'});assert.equal(store().state,'talking');store().setActivity('speech',null);assert.equal(store().state,'idle');
dispatchMascot({type:'quiz.completed',score:4,total:5});assert.equal(store().state,'celebrating');
dispatchMascot({type:'quiz.completed',score:1,total:5});assert.equal(store().state,'encouraging');
store().setActivity('notice',null);
console.log('PASS: actual-event transitions, priorities, task completion, microphone/speech cleanup, and honest quiz feedback');
